// Helper: Query credentials from Supabase or fallback
export async function getCredentials(): Promise<DbCredential[]> {
  try {
    const { data, error } = await supabase.from('credentials').select('*').order('issued_at', { ascending: false });
    if (error || !data || data.length === 0) {
      return getFallbackCredentials();
    }
    return data as DbCredential[];
  } catch (err) {
    console.warn('Supabase query fallback:', err);
    return getFallbackCredentials();
  }
}

// Helper: Insert a new credential
export async function insertCredential(cred: Omit<DbCredential, 'id' | 'issued_at'>): Promise<DbCredential> {
  try {
    const { data, error } = await supabase.from('credentials').insert([cred]).select();
    if (error || !data || !data[0]) {
      throw error || new Error('Insert returned no data');
    }
    return data[0] as DbCredential;
  } catch (err) {
    console.warn('Saving to local storage as fallback:', err);
    const local = {
      ...cred,
      id: Date.now(),
      issued_at: new Date().toISOString(),
    };
    saveLocalCredential(local);
    return local;
  }
}

// Helper: Log verification
export async function logVerification(searchQuery: string, credentialId?: string, result: 'VALID' | 'NOT_FOUND' | 'REVOKED' = 'VALID') {
  try {
    await supabase.from('verification_logs').insert([
      {
        search_query: searchQuery,
        credential_id: credentialId || null,
        result,
      },
    ]);
  } catch {
    // Ignore verification log failures
  }
}

